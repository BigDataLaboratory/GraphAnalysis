import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import io

prefix = "/ipazianas/pasquini/output_graph_analysis/communities_leiden/feb-aug_2022/cpm/result/images"

def generate_jaccard_visualizations(csv_data, output_prefix='jaccard_comparison'):
    """
    Reads CSV data containing Jaccard similarity scores, creates one consolidated summary plot,
    and saves it as a PNG file.

    Args:
        csv_data (str): A string containing the CSV formatted data.
        output_prefix (str): A prefix for the output image filenames.
    """
    try:
        df = pd.read_csv(io.StringIO(csv_data))
        print("Jaccard data loaded successfully. Generating consolidated plot...")
    except Exception as e:
        print(f"Error loading data: {e}")
        return

    # Set a professional plot style
    sns.set_theme(style="whitegrid", context="talk")

    # --- Reshape the data from wide to long format for easier plotting ---
    df_long = pd.melt(
        df,
        id_vars=['pair', 'resolution'],
        value_vars=['mean_jaccard_1to2', 'median_jaccard_1to2', 'max_jaccard_1to2'],
        var_name='metric_type',
        value_name='jaccard_index'
    )
    # Clean up the metric names for the legend
    df_long['metric_type'] = df_long['metric_type'].replace({
        'mean_jaccard_1to2': 'Mean',
        'median_jaccard_1to2': 'Median',
        'max_jaccard_1to2': 'Maximum'
    })


    # --- Create a single, consolidated figure ---
    plt.figure(figsize=(18, 12))
    
    ax = sns.lineplot(
        data=df_long,
        x='resolution',
        y='jaccard_index',
        hue='pair',          # Different colors for each comparison pair
        style='metric_type', # Different line styles for mean, median, max
        markers=True,
        markersize=10,
        lw=2.5
    )
    
    # --- Formatting the plot ---
    #plt.suptitle('Jaccard Similarity Analysis Between Top 500 Communities', fontsize=28, weight='bold')
    #plt.title('Mean, Median, and Maximum overlap is consistently low (<4%) across all comparisons', fontsize=20, pad=20)
    
    plt.xlabel('Resolution (Gamma)', fontsize=16)
    plt.ylabel('Jaccard Index', fontsize=16)
    
    # Format y-axis as percentage
    ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda y, _: '{:.1%}'.format(y)))
    
    # Improve legend
    handles, labels = ax.get_legend_handles_labels()
    ax.legend(handles=handles, labels=labels, title='Comparison & Metric', fontsize=14, title_fontsize=16)
    
    # Set tick parameters
    ax.tick_params(axis='x', labelsize=14)
    ax.tick_params(axis='y', labelsize=14)

    # Adjust layout and save the single figure
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    plot_path = f"{prefix}/{output_prefix}_consolidated_plot.png"
    plt.savefig(plot_path, dpi=300)
    print(f"✅ Consolidated plot saved to: {plot_path}")
    plt.close()


